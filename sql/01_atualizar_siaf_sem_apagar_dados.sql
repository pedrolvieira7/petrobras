-- SIAF: MIGRAÇÃO INCREMENTAL - executar no SQL Editor do Supabase ANTES de publicar o código.
-- Não remove tabelas ou cadastros. Faça um backup antes e execute apenas no banco do projeto SIAF.
BEGIN;

ALTER TABLE siaf.falha ADD COLUMN IF NOT EXISTS descricao text;
ALTER TABLE siaf.falha ADD COLUMN IF NOT EXISTS modo_falha varchar(100);
ALTER TABLE siaf.falha ADD COLUMN IF NOT EXISTS horas_parada numeric(12,2) NOT NULL DEFAULT 0;
ALTER TABLE siaf.analise ADD COLUMN IF NOT EXISTS parecer_gestor text;
ALTER TABLE siaf.historico_auditoria ADD COLUMN IF NOT EXISTS dados_antes text;
ALTER TABLE siaf.historico_auditoria ADD COLUMN IF NOT EXISTS dados_depois text;

CREATE TABLE IF NOT EXISTS siaf.notificacao (
 id_notificacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario integer NOT NULL REFERENCES siaf.usuario(id_usuario) ON DELETE CASCADE,
 titulo varchar(120) NOT NULL,
 mensagem varchar(500) NOT NULL,
 link varchar(250),
 criado_em timestamp without time zone NOT NULL DEFAULT (now() at time zone 'UTC'),
 lido_em timestamp without time zone
);
CREATE INDEX IF NOT EXISTS ix_siaf_notificacao_usuario_lida ON siaf.notificacao(id_usuario,lido_em,criado_em);

-- Anexos persistentes em bytea: não dependem do disco efêmero do Railway.
CREATE TABLE IF NOT EXISTS siaf.anexo_conteudo (
 id_anexo integer PRIMARY KEY REFERENCES siaf.anexo(id_anexo) ON DELETE CASCADE,
 tipo_conteudo varchar(80) NOT NULL,
 conteudo bytea NOT NULL,
 CONSTRAINT ck_siaf_anexo_5mb CHECK (octet_length(conteudo) <= 5242880)
);

-- Proteção contra tags repetidas. Não cria índice UNIQUE automaticamente
-- para não interromper instalações com duplicidades antigas.
CREATE INDEX IF NOT EXISTS ix_siaf_equipamento_tag ON siaf.equipamento(tag);

COMMIT;

SELECT
 (SELECT count(*) FROM information_schema.tables WHERE table_schema = 'siaf' AND table_type = 'BASE TABLE') as total_tabelas,
 (SELECT count(*) FROM siaf.perfil) as perfis;
-- Esperado: 12 tabelas no schema siaf (as 10 originais e as 2 novas).
